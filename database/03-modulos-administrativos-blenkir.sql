-- Colegio Blenkir: ampliación inspirada en SIGA UC, sin módulo QR.
-- Ejecutar sobre blenkir_ssacb DESPUÉS del esquema original de SSACB.
-- No copia alumnos, DNIs ni cuentas de SIGA UC. PostgreSQL 16+.
BEGIN;

CREATE TABLE IF NOT EXISTS personal_colegio (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dni VARCHAR(8) NOT NULL UNIQUE,
  nombre_completo VARCHAR(160) NOT NULL,
  cargo VARCHAR(50) NOT NULL,
  correo VARCHAR(120),
  telefono VARCHAR(20),
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS horarios_clases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  curso_id BIGINT NOT NULL REFERENCES cursos(id),
  dia_semana INTEGER NOT NULL CHECK(dia_semana BETWEEN 1 AND 7),
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  aula VARCHAR(80),
  CONSTRAINT ck_horario_orden CHECK(hora_fin > hora_inicio)
);
CREATE INDEX IF NOT EXISTS idx_horarios_curso_dia ON horarios_clases(curso_id,dia_semana);

CREATE TABLE IF NOT EXISTS conceptos_cobro_blenkir (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(70) NOT NULL UNIQUE,
  importe NUMERIC(12,2) NOT NULL CHECK(importe > 0),
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS cuentas_por_cobrar (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id),
  concepto_id BIGINT NOT NULL REFERENCES conceptos_cobro_blenkir(id),
  importe NUMERIC(12,2) NOT NULL CHECK(importe > 0),
  pagado NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK(pagado >= 0 AND pagado <= importe),
  vencimiento DATE NOT NULL,
  periodo VARCHAR(50) NOT NULL,
  version BIGINT,
  CONSTRAINT uk_cobro_estudiante_concepto_periodo UNIQUE(estudiante_id,concepto_id,periodo)
);
CREATE INDEX IF NOT EXISTS idx_cuentas_estudiante ON cuentas_por_cobrar(estudiante_id);

CREATE TABLE IF NOT EXISTS pagos_blenkir (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cuenta_id BIGINT NOT NULL REFERENCES cuentas_por_cobrar(id),
  importe NUMERIC(12,2) NOT NULL CHECK(importe > 0),
  medio VARCHAR(30) NOT NULL,
  fecha TIMESTAMP NOT NULL,
  registrado_por VARCHAR(80) NOT NULL,
  referencia VARCHAR(100)
);
CREATE INDEX IF NOT EXISTS idx_pagos_cuenta_fecha ON pagos_blenkir(cuenta_id,fecha);

CREATE TABLE IF NOT EXISTS movimientos_caja_blenkir (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha TIMESTAMP NOT NULL,
  tipo VARCHAR(10) NOT NULL CHECK(tipo IN ('INGRESO','EGRESO')),
  concepto VARCHAR(160) NOT NULL,
  importe NUMERIC(12,2) NOT NULL CHECK(importe > 0),
  usuario VARCHAR(80) NOT NULL,
  pago_id BIGINT UNIQUE REFERENCES pagos_blenkir(id)
);
CREATE INDEX IF NOT EXISTS idx_caja_fecha ON movimientos_caja_blenkir(fecha);

CREATE TABLE IF NOT EXISTS comunicados_blenkir (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(120) NOT NULL,
  mensaje VARCHAR(3000) NOT NULL,
  rol_destino VARCHAR(30) NOT NULL,
  fecha TIMESTAMP NOT NULL,
  autor VARCHAR(80) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_comunicados_fecha ON comunicados_blenkir(fecha DESC);

CREATE TABLE IF NOT EXISTS auditoria_blenkir (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha TIMESTAMP NOT NULL,
  usuario VARCHAR(80) NOT NULL,
  accion VARCHAR(60) NOT NULL,
  entidad VARCHAR(60) NOT NULL,
  referencia VARCHAR(80) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_auditoria_fecha ON auditoria_blenkir(fecha DESC);

CREATE TABLE IF NOT EXISTS competencias_blenkir (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  curso_id BIGINT NOT NULL REFERENCES cursos(id),
  nombre VARCHAR(200) NOT NULL,
  descripcion VARCHAR(800)
);

CREATE TABLE IF NOT EXISTS logros_competencias_blenkir (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competencia_id BIGINT NOT NULL REFERENCES competencias_blenkir(id),
  estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id),
  periodo VARCHAR(30) NOT NULL,
  nivel VARCHAR(2) NOT NULL CHECK(nivel IN ('AD','A','B','C')),
  conclusion VARCHAR(1000),
  CONSTRAINT uk_logros_estudiante_competencia_periodo UNIQUE(competencia_id,estudiante_id,periodo)
);

COMMIT;
