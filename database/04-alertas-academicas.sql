BEGIN;

CREATE TABLE IF NOT EXISTS alertas_academicas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id),
  curso_id BIGINT NOT NULL REFERENCES cursos(id),
  periodo VARCHAR(30) NOT NULL,
  motivo VARCHAR(500) NOT NULL,
  promedio DOUBLE PRECISION NOT NULL CHECK (promedio >= 0 AND promedio <= 20),
  umbral DOUBLE PRECISION NOT NULL CHECK (umbral >= 0 AND umbral <= 20),
  estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
    CHECK (estado IN ('PENDIENTE', 'ATENDIDA', 'RESUELTA')),
  fecha_generacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_alerta_academica_activa
  ON alertas_academicas (estudiante_id, curso_id, periodo)
  WHERE estado <> 'RESUELTA';

CREATE INDEX IF NOT EXISTS idx_alertas_estudiante_fecha
  ON alertas_academicas (estudiante_id, fecha_generacion DESC);

CREATE INDEX IF NOT EXISTS idx_alertas_curso_fecha
  ON alertas_academicas (curso_id, fecha_generacion DESC);

COMMIT;
